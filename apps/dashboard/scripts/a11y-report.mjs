#!/usr/bin/env node
/**
 * Writes docs/accessibility/accessibility-report.md from the Playwright evidence:
 *   e2e-results/a11y.jsonl   — axe-core WCAG 2.1 A/AA results per route × colour scheme (a11y.spec.ts)
 *   e2e-results/results.json — pass/fail of the responsive, zoom and keyboard specs (JSON reporter)
 *   e2e-results/rerun-*.json — single-test reruns (PLAYWRIGHT_JSON_OUTPUT_FILE); they replace that test's
 *                              result and are listed in the report with the original failure
 *   e2e-results/motion-contrast.jsonl — reduced-motion and forced-colors checks (motion-contrast.spec.ts)
 * E2E_STATE_DIR, when set for the run, is read the same way the suite writes it (e2e/paths.ts).
 * Usage: pnpm --filter @talkivio/dashboard e2e && node scripts/a11y-report.mjs
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, '../../docs/accessibility/accessibility-report.md');
const resultsDir = process.env.E2E_STATE_DIR ? resolve(process.env.E2E_STATE_DIR, 'results') : resolve(root, 'e2e-results');
const axeFile = resolve(resultsDir, 'a11y.jsonl');
const resultsFile = resolve(resultsDir, 'results.json');
const motionFile = resolve(resultsDir, 'motion-contrast.jsonl');
if (!existsSync(axeFile)) throw new Error('Run the Playwright suite first (e2e-results/a11y.jsonl missing).');

const axe = readFileSync(axeFile, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
const byImpact = { critical: 0, serious: 0, moderate: 0, minor: 0 };
const byRule = new Map();
for (const r of axe) {
  for (const v of r.violations) {
    byImpact[v.impact] = (byImpact[v.impact] ?? 0) + v.nodes;
    const k = `${v.impact} · ${v.id}`;
    const e = byRule.get(k) ?? { help: v.help, routes: new Set(), nodes: 0 };
    e.routes.add(`${r.route} (${r.theme})`);
    e.nodes += v.nodes;
    byRule.set(k, e);
  }
}
const readResults = (path) => {
  const out = [];
  const walk = (s, file = '') => {
    for (const sp of s.specs ?? []) for (const t of sp.tests) {
      const r = t.results.at(-1);
      out.push({ file: s.file ?? file, title: sp.title, status: r?.status ?? 'unknown', error: (r?.error?.message ?? '').split('\n')[0].replace(/\u001b\[[0-9;]*m/g, '').slice(0, 160) });
    }
    for (const c of s.suites ?? []) walk(c, s.file ?? file);
  };
  for (const s of JSON.parse(readFileSync(path, 'utf8')).suites) walk(s);
  return out;
};
const tests = existsSync(resultsFile) ? readResults(resultsFile) : [];
const reruns = [];
for (const name of existsSync(resultsDir) ? readdirSync(resultsDir).filter((n) => /^rerun-.*\.json$/.test(n)).sort() : []) {
  for (const r of readResults(resolve(resultsDir, name))) {
    const i = tests.findIndex((t) => t.file === r.file && t.title === r.title);
    if (i >= 0) reruns.push({ title: r.title, before: tests[i].status, beforeError: tests[i].error, after: r.status, source: name });
    if (i >= 0) tests[i] = r;
    else tests.push(r);
  }
}
const nonAxe = tests.filter((t) => !t.file.includes('a11y.spec') && !t.file.includes('motion-contrast.spec'));
// Latest record per check × route (reruns append).
const motion = new Map();
for (const r of existsSync(motionFile) ? readFileSync(motionFile, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)) : []) motion.set(`${r.check} ${r.route}`, r);
const mr = [...motion.values()];
const reduced = mr.filter((r) => r.check === 'reduced-motion');
const focus = mr.filter((r) => r.check === 'forced-colors-focus');
const states = mr.filter((r) => r.check === 'forced-colors-state');
const lines = [
  '# Accessibility report',
  '',
  `_Generated by \`apps/dashboard/scripts/a11y-report.mjs\` on ${new Date().toISOString()} from the Playwright suite (\`apps/dashboard/e2e\`, installed Chrome, production build of the dashboard (next build + next start) against the local API). Re-run to refresh._`,
  '',
  '## Automated audit (axe-core, WCAG 2.1 A/AA)',
  '',
  `${axe.length} scans of ${new Set(axe.map((r) => r.route)).size} routes: ${[...new Set(axe.map((r) => r.theme))].map((th) => `${axe.filter((r) => r.theme === th).length} ${th === 'light-ar' ? 'Arabic (RTL, light)' : th}`).join(', ')}. Critical and serious findings fail the suite.`,
  '',
  '| Impact | Nodes |',
  '| --- | --- |',
  ...Object.entries(byImpact).map(([k, v]) => `| ${k} | ${v} |`),
  '',
  byRule.size ? '| Rule | Help | Nodes | Where |' : '_No violations of any impact._',
  ...(byRule.size ? ['| --- | --- | --- | --- |'] : []),
  ...[...byRule.entries()].map(([k, e]) => `| ${k} | ${e.help} | ${e.nodes} | ${[...e.routes].slice(0, 6).join(', ')}${e.routes.size > 6 ? ` +${e.routes.size - 6}` : ''} |`),
  '',
  '## Interaction checks',
  '',
  nonAxe.length ? '| Spec | Check | Result |' : '_Responsive / keyboard specs not in this run._',
  ...(nonAxe.length ? ['| --- | --- | --- |'] : []),
  ...nonAxe.map((t) => `| ${t.file.replace(/^.*e2e\//, '')} | ${t.title} | ${t.status === 'passed' ? '✅ passed' : t.status === 'skipped' ? '⏭ skipped' : `❌ ${t.status}`} |`),
  '',
  ...(reruns.length
    ? ['Reruns (the full-suite result is replaced by the single-test rerun):', '', ...reruns.map((r) => `- ${r.title}: ${r.before}${r.beforeError ? ` (${r.beforeError})` : ''} → ${r.after} in \`${r.source}\``), '']
    : []),
  '## Reduced motion and forced colors (Chromium emulation)',
  '',
  mr.length
    ? `prefers-reduced-motion: reduce — ${reduced.filter((r) => !r.slowCount && !r.endless && !r.smoothScroll).length} of ${reduced.length} surfaces (dashboard routes and the widget frame) have no transition or animation longer than 0.01 ms, nothing animating indefinitely and no smooth scrolling.`
    : '_motion-contrast.spec.ts not in this run._',
  ...(mr.length
    ? [
        '',
        `forced-colors: active — ${focus.filter((r) => !r.missing.length).length} of ${focus.length} routes show a focus outline on every control reached with Tab (${focus.reduce((s, r) => s + r.reached, 0)} focus stops in total).` +
          (states.length ? ` Control states captured before and after a change: ${Object.entries(states.at(-1).changed).map(([k, v]) => `${k} ${v ? 'distinguishable' : 'NOT distinguishable'}`).join(', ')}.` : ''),
        ...reduced.filter((r) => r.slowCount || r.endless || r.smoothScroll).map((r) => `- ❌ reduced motion on ${r.route}: ${r.slow.slice(0, 3).join('; ')}`),
        ...focus.filter((r) => r.missing.length).map((r) => `- ❌ no focus outline in forced colors on ${r.route}: ${r.missing.slice(0, 3).join('; ')}`),
      ]
    : []),
  '',
  '## Not covered by automation (manual evidence required for sign-off)',
  '',
  '- Screen reader walkthroughs (VoiceOver/NVDA): transcript load, new-message announcement, chat-offer announcement (assertive live region; reached with Alt+Shift+O or the \`Skip to chat offers\` link — focus never moves on arrival). The live-region contract they rely on is automated in `announce.spec.ts` (transcript logs are not live regions, so history is silent; one polite, shortened sentence per message from someone else; own messages silent) — the walkthrough confirms it with real assistive technology.',
  '- Native-speaker review of the Arabic copy (catalogues are complete and tested for keys, variables and plural categories; wording is machine-authored).',
  '- Windows High Contrast themes on Windows itself (forced colors is emulated in Chromium above; real themes and Edge/Firefox were not run).',
  '',
];
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(`accessibility report: ${axe.length} scans, ${byRule.size} rule groups → ${out}`);
