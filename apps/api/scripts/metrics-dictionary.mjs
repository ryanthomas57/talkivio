#!/usr/bin/env node
/**
 * Generates docs/analytics/metrics-dictionary.md from the code that computes the numbers, so the
 * dictionary cannot drift from the product:
 *   - product analytics measures: MEASURE_DEFINITIONS (label, kind, unit, population, definition, null policy)
 *   - operational metrics: every Prometheus series MetricsService registers (+ the DB-derived gauges),
 *     with the label keys actually passed at call sites in src/.
 * Usage (after `npx nest build`): node scripts/metrics-dictionary.mjs
 */
import { createRequire } from 'node:module';
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const outPath = resolve(apiDir, '../../docs/analytics/metrics-dictionary.md');

const { MEASURE_DEFINITIONS, DEFINITIONS_VERSION } = require(join(apiDir, 'dist/features/analytics/measures.js'));
const { MetricsService } = require(join(apiDir, 'dist/core/metrics.service.js'));

// ── operational metrics: names/types/help from a live registry instance ──
const svc = new MetricsService();
const series = Object.entries(svc)
  .filter(([, v]) => v && typeof v === 'object' && v.def && typeof v.def.name === 'string')
  .map(([field, v]) => ({ field, name: v.def.name, type: v.def.type, help: v.def.help, buckets: v.def.buckets ?? null }));

// Label keys actually used at call sites (`metrics.<field>.inc|observe|set(metrics.labels({...}))`).
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (p.endsWith('.ts') && !p.endsWith('.spec.ts')) files.push(p);
  }
};
walk(join(apiDir, 'src'));
const labels = new Map();
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const m of src.matchAll(/metrics\.(\w+)\.(?:inc|observe|set)\(\s*(?:this\.)?metrics\.labels\(\{([^}]*)\}/g)) {
    const keys = [...m[2].matchAll(/(\w+)\s*:/g)].map((k) => k[1]);
    labels.set(m[1], new Set([...(labels.get(m[1]) ?? []), ...keys]));
  }
  // MetricsService helpers such as command(name, outcome) label commands internally.
}
labels.set('commands', new Set([...(labels.get('commands') ?? []), 'command', 'outcome']));

// Gauges refreshed at scrape time from PostgreSQL (rd_metrics_snapshot, core/operational-gauges.ts).
const DB_DERIVED = new Set(['talkivio_routing_queue_oldest_seconds', 'talkivio_scan_backlog_seconds', 'talkivio_outbox_oldest_unpublished_seconds']);

const esc = (s) => String(s ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const lines = [];
lines.push('# Metrics dictionary', '');
lines.push(`_Generated by \`apps/api/scripts/metrics-dictionary.mjs\` from the running code (analytics definitions version ${DEFINITIONS_VERSION}). Do not edit by hand._`, '');
lines.push('## Product analytics measures', '');
lines.push('Every analytics response carries `definitions_version`, the population and sample size. Times are UTC; report boundaries are half-open `[from, to)` in the report time zone.', '');
lines.push('| Key | Label | Kind | Unit | Population | Definition | Null / empty policy |', '| --- | --- | --- | --- | --- | --- | --- |');
for (const [key, d] of Object.entries(MEASURE_DEFINITIONS)) {
  lines.push(`| \`${key}\` | ${esc(d.label)} | ${d.kind} | ${d.unit} | ${esc(d.population)} | ${esc(d.definition)} | ${esc(d.nullPolicy)} |`);
}
lines.push('', '## Operational metrics (Prometheus)', '');
lines.push('Exposed on `/health/metrics` (api/gateway) and the worker health listener (`WORKER_HEALTH_PORT`), internal network or `METRICS_TOKEN` only. Alert rules: `infra/observability/alert-rules.yml`; runbooks: `docs/operations/runbooks.md`.', '');
lines.push('| Metric | Type | Labels | Meaning |', '| --- | --- | --- | --- |');
for (const s of series) {
  const l = [...(labels.get(s.field) ?? [])].sort();
  const note = DB_DERIVED.has(s.name) ? ' Derived from PostgreSQL at scrape time (5 s cache).' + (s.name === 'talkivio_routing_queue_oldest_seconds' ? ' `routable=true`: an eligible online agent exists; `false`: expected outside hours.' : '') : '';
  lines.push(`| \`${s.name}\` | ${s.type} | ${l.length ? l.map((x) => `\`${x}\``).join(', ') : '—'} | ${esc(s.help)}${note}${s.buckets ? ` Buckets: ${s.buckets.join(', ')} s.` : ''} |`);
}
lines.push('', 'Content never appears in metrics: labels are route groups, outcomes, queues and namespaces — never ids, emails or message text.', '');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'));
console.log(`metrics dictionary: ${Object.keys(MEASURE_DEFINITIONS).length} measures, ${series.length} operational series → ${outPath}`);
