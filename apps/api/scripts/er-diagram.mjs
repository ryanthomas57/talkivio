#!/usr/bin/env node
/**
 * Generates docs/architecture/er-diagram.md (Mermaid erDiagram) from the migrated
 * database catalog, so every foreign key — including the composite tenant FKs that
 * migrations add in SQL — is shown exactly as enforced.
 *
 * Usage: DATABASE_OWNER_URL=postgresql://… node scripts/er-diagram.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '../../../docs/architecture/er-diagram.md');
const url = (process.env.DATABASE_OWNER_URL ?? process.env.DATABASE_URL ?? '').replace(/\?.*$/, '');
if (!url) throw new Error('Set DATABASE_OWNER_URL (a migrated database).');

function query(sql) {
  const out = execFileSync('psql', [url, '-X', '-A', '-t', '-F', '\t', '-c', sql], { encoding: 'utf8' });
  return out.trim() ? out.trim().split('\n').map((l) => l.split('\t')) : [];
}

const tables = query(`SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> '_prisma_migrations' ORDER BY 1`).map((r) => r[0]);

const pk = new Map();
for (const [t, col] of query(`SELECT tc.relname, a.attname FROM pg_constraint k
  JOIN pg_class tc ON tc.oid = k.conrelid JOIN pg_namespace n ON n.oid = tc.relnamespace
  JOIN unnest(k.conkey) AS col(num) ON true JOIN pg_attribute a ON a.attrelid = tc.oid AND a.attnum = col.num
  WHERE k.contype = 'p' AND n.nspname = 'public'`)) {
  pk.set(t, [...(pk.get(t) ?? []), col]);
}

const fks = query(`SELECT k.conname, src.relname, dst.relname,
    (SELECT string_agg(a.attname, ',' ORDER BY x.ord) FROM unnest(k.conkey) WITH ORDINALITY x(num, ord) JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = x.num),
    (SELECT bool_and(a.attnotnull) FROM unnest(k.conkey) x(num) JOIN pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = x.num)
  FROM pg_constraint k JOIN pg_class src ON src.oid = k.conrelid JOIN pg_class dst ON dst.oid = k.confrelid
  JOIN pg_namespace n ON n.oid = src.relnamespace WHERE k.contype = 'f' AND n.nspname = 'public' ORDER BY 2, 1`).map(([name, src, dst, cols, notnull]) => ({ name, src, dst, cols: cols.split(','), required: notnull === 't' }));

const rls = new Set(query(`SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relrowsecurity AND c.relforcerowsecurity`).map((r) => r[0]));

// The per-table tenant FK (tenant_id → tenants.id) exists on every tenant-owned table; it is
// stated once in prose instead of drawing ~55 identical edges.
const tenantOnly = (f) => f.dst === 'tenants' && f.cols.length === 1 && f.cols[0] === 'tenant_id';
const edges = fks.filter((f) => !tenantOnly(f));
const fkCols = new Map();
for (const f of fks) for (const c of f.cols) fkCols.set(`${f.src}.${c}`, true);

const lines = ['erDiagram'];
for (const t of tables) {
  const cols = new Set([...(pk.get(t) ?? []), ...edges.filter((e) => e.src === t).flatMap((e) => e.cols)]);
  lines.push(`  ${t} {`);
  for (const c of cols) lines.push(`    col ${c}${(pk.get(t) ?? []).includes(c) ? ' PK' : fkCols.has(`${t}.${c}`) ? ' FK' : ''}`);
  lines.push('  }');
}
for (const e of edges) lines.push(`  ${e.dst} ${e.required ? '||' : '|o'}--o{ ${e.src} : "${e.cols.filter((c) => c !== 'tenant_id').join(', ') || e.cols.join(', ')}"`);

const tenantOwned = fks.filter(tenantOnly).map((f) => f.src);
const doc = `# Talkivio entity–relationship diagram

_Generated by \`apps/api/scripts/er-diagram.mjs\` from the migrated database catalog — do not edit by hand._

- ${tables.length} tables, ${fks.length} foreign keys (${edges.length} drawn below).
- ${tenantOwned.length} tenant-owned tables reference \`tenants(id)\` through \`tenant_id\` (not drawn individually); cross-table
  references inside a tenant are composite \`(tenant_id, …) → (tenant_id, id)\` so a row can never point into another tenant.
- ${rls.size} tables have row-level security enabled **and forced** for the application role (ADR 0002).

\`\`\`mermaid
${lines.join('\n')}
\`\`\`

## Row-level security
${[...rls].sort().map((t) => `\`${t}\``).join(', ')}
`;
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, doc);
console.log(`Wrote ${outPath}: ${tables.length} tables, ${fks.length} FKs, ${rls.size} RLS tables`);
