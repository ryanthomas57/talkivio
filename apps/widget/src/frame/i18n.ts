const DICTS: Record<Locale, Dict> = { en, ar, es, fr, de, pt, it, nl, ja };

/** Keys a catalogue lacks (used by tests to keep every language complete; tree-shaken from the bundle). */
export function missingKeys(locale: Locale): StringKey[] {
  return (Object.keys(en) as StringKey[]).filter((k) => !(k in DICTS[locale]));
}

export function isRtl(locale: Locale): boolean {
  return locale === 'ar';
}

function normalize(input: string): string {
  return input.trim().toLowerCase().replace('_', '-').split('-')[0];
}

export function isSupportedLocale(input: string | null | undefined): boolean {
  return !!input && (LOCALES as readonly string[]).includes(normalize(input));
}

export interface LocaleResolution {
  locale: Locale;
  /** First explicitly requested (SDK / site) locale that is not supported, if any. */
  unsupported: string | null;
}

/**
 * Locale precedence: SDK override → published site locale → browser language → en.
 * Unsupported explicit locales fall through deterministically to the next candidate.
 */
export function resolveLocale(sdk: string | null | undefined, site: string | null | undefined, browser: string | null | undefined): LocaleResolution {
  let unsupported: string | null = null;
  const explicit = [sdk, site === 'auto' ? null : site];
  for (const c of explicit) {
    if (!c) continue;
    if (isSupportedLocale(c)) return { locale: normalize(c) as Locale, unsupported };
    unsupported ??= c;
  }
  if (browser && isSupportedLocale(browser)) return { locale: normalize(browser) as Locale, unsupported };
  return { locale: 'en', unsupported };
}

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

const pluralRules = new Map<string, Intl.PluralRules>();
function pluralCategory(locale: Locale, n: number): string {
  try {
    let pr = pluralRules.get(locale);
    if (!pr) pluralRules.set(locale, (pr = new Intl.PluralRules(locale)));
    return pr.select(n);
  } catch {
    return n === 1 ? 'one' : 'other';
  }
}

export function formatNumber(locale: Locale, n: number): string {
  try {
    return new Intl.NumberFormat(locale).format(n);
  } catch {
    return String(n);
  }
}

/** Translate a chrome string, falling back to English for missing keys. */
export function t(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  const entry = DICTS[locale]?.[key] ?? en[key];
  if (typeof entry === 'string') return interpolate(entry, vars);
  return tp(locale, key, Number(vars?.n ?? 0), vars);
}

/** Plural-aware translation (`{n}` is formatted with Intl.NumberFormat). */
export function tp(locale: Locale, key: StringKey, n: number, vars?: Record<string, string | number>): string {
  const entry = DICTS[locale]?.[key] ?? en[key];
  const all = { ...vars, n: formatNumber(locale, n) };
  if (typeof entry === 'string') return interpolate(entry, all);
  const cat = pluralCategory(locale, n) as keyof PluralForms;
  const form = entry[cat] ?? entry.other;
  return interpolate(form, all);
}

export type Translator = ((key: StringKey, vars?: Record<string, string | number>) => string) & {
  plural: (key: StringKey, n: number, vars?: Record<string, string | number>) => string;
  locale: Locale;
  rtl: boolean;
};

export function translator(locale: Locale): Translator {
  const fn = ((key: StringKey, vars?: Record<string, string | number>) => t(locale, key, vars)) as Translator;
  fn.plural = (key, n, vars) => tp(locale, key, n, vars);
  fn.locale = locale;
  fn.rtl = isRtl(locale);
  return fn;
}
